import { strict as assert } from 'node:assert';
import { Chess } from 'chess.js';
import { parseGame, DEMO, classify, notation, explain, hanging, type Evaluation } from '../lib/chess/core';
const demo=parseGame(DEMO);
assert.equal(demo.moves.length,14);
assert.ok(new Chess(demo.fens.at(-1)).isCheckmate());
assert.throws(()=>parseGame('not a game'));
assert.throws(()=>parseGame('[Event "Empty"]'));
const before=demo.fens[6];const branch=new Chess(before);branch.move('d3');assert.equal(demo.fens[6],before);assert.notEqual(branch.fen(),demo.fens[7]);
const score=(n:number,best='e2e4'):Evaluation=>({best,depth:12,lines:[{score:n,depth:12,pv:[best],rank:1}]});
assert.equal(classify(score(20),score(-400),demo.moves[0]).label,'Best');
assert.equal(classify(score(20,'d2d4'),score(-400),demo.moves[0]).label,'Blunder');
assert.equal(classify(score(20),score(400),demo.moves[1]).label,'Blunder');
assert.equal(classify(score(20),undefined,demo.moves[0]).label,'Pending');
assert.equal(notation(demo.fens[0],['e2e4','e7e5','g1f3']),'1.e4 e5 2.Nf3');
assert.ok(explain(demo.fens[0],'g1f3').includes('develops'));
const promotion=new Chess('7k/P7/8/8/8/8/8/7K w - - 0 1');assert.equal(promotion.moves({verbose:true}).filter(m=>m.promotion).length,4);
const castle=new Chess('r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1');castle.move('O-O');assert.equal(castle.get('f1')?.type,'r');
const ep=new Chess();['e4','a6','e5','d5','exd6'].forEach(m=>ep.move(m));assert.equal(ep.get('d5'),undefined);
assert.ok(hanging('7k/8/8/8/3q4/8/3R4/7K w - - 0 1').includes('rook on d2'));
console.log('PASS: PGN replay, invalid PGN, isolated variations, colour-aware move classification, SAN lines, promotion, castling, en passant, undefended-piece detection.');
